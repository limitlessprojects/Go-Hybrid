package decider

import "testing"

func TestFalsifierF1_SpanAndCodeAttribution(t *testing.T) {
	imp := NewCachedImporter()
	_ = imp.WarmStdlib("fmt")
	dec := NewDecider(imp)

	cases := []struct {
		name     string
		src      string
		wantCode string
		wantFile string
		wantLine int
		wantCol  int
	}{
		{
			name: "call-arity-mismatch",
			src: `package main
//line add.hy:1:1
func add(a int, b int) int { return a + b }
//line add.hy:5:1
func main() {
//line add.hy:6:10
	_ = add(1)
}
`,
			wantCode: "HYB-E1002",
			wantFile: "add.hy",
			wantLine: 6,
			wantCol:  10,
		},
		{
			name: "incomparable-map-key-3438",
			src: `package main
func main() {
/*line mapkey.hy:5:14*/	_ = map[[]int]int{}
}
`,
			wantCode: "HYB-E2006",
			wantFile: "mapkey.hy",
			wantLine: 5,
			wantCol:  14,
		},
		{
			name: "blank-field-struct-eq-3441",
			src: `package main
type Bad struct { _ []int }
func main() {
	var a, b Bad
/*line blank_eq.hy:8:11*/	_ = a == b
}
`,
			wantCode: "HYB-E2006",
			wantFile: "blank_eq.hy",
			wantLine: 8,
			wantCol:  11,
		},
		{
			name: "negative-shift-count",
			src: `package main
func main() {
/*line shift.hy:2:9*/	_ = 1 << -1
}
`,
			wantCode: "HYB-E6005",
			wantFile: "shift.hy",
			wantLine: 2,
			wantCol:  9,
		},
		{
			name: "negative-array-len",
			src: `package main
func main() {
/*line arr.hy:2:8*/	var a [-1]int
	_ = a
}
`,
			wantCode: "HYB-E6004",
			wantFile: "arr.hy",
			wantLine: 2,
			wantCol:  8,
		},
		{
			name: "redeclaration-in-block",
			src: `package main
func main() {
	var x int = 1
/*line redecl.hy:3:6*/	var x string = "dup"
	_ = x
}
`,
			wantCode: "HYB-E1003",
			wantFile: "redecl.hy",
			wantLine: 3,
			wantCol:  6,
		},
		{
			name: "synthetic-try-wrapper-zero-bleed",
			src: `package main
func helper() (int, error) { return 0, nil }
func main() {
	// Synthetic wrapper generated by hy-emit
	__hy_val_0, __hy_err_0 := helper()
	if __hy_err_0 != nil { return }
	_ = __hy_val_0
/*line try.hy:14:17*/	var bad int = "wrong"
	_ = bad
}
`,
			wantCode: "HYB-E1002",
			wantFile: "try.hy",
			wantLine: 14,
			wantCol:  17,
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			diags, err := dec.CheckSource("emitted.hy.go", []byte(tc.src))
			if err != nil {
				t.Fatalf("unexpected error: %v", err)
			}
			if len(diags) == 0 {
				t.Fatalf("expected diagnostic, got none")
			}
			got := diags[0]
			if got.Code != tc.wantCode || got.File != tc.wantFile || got.Line != tc.wantLine {
				t.Errorf("got %+v, want code=%s file=%s line=%d col=%d", got, tc.wantCode, tc.wantFile, tc.wantLine, tc.wantCol)
			}
		})
	}
}
