"""Rebuild the Go artifact and its reference-oracle tests, no dependencies."""
import json
from pathlib import Path
from planner import emit_go, plan, reference, verify
from test_planner import fixtures

root = Path(__file__).parent
code = ['// Code generated by generate.py; DO NOT EDIT.\npackage staticnetwork']
tests = ['package staticnetwork\nimport "testing"']
certs = []
for i, (actors, edges) in enumerate(fixtures()):
    name = f'Kernel{i}'
    cert = plan(actors, edges)
    code.append(emit_go(actors, edges, cert, name))
    next_token, checksum, queues = reference(actors, edges, cert, 50)
    lines = [f'func Test{name}Reference(t *testing.T) {{', f'k := New{name}()',
             'for range 50 { k.Step() }',
             f'if k.Next != {next_token} || k.Checksum != {checksum} {{ t.Fatalf("reference mismatch: next=%d checksum=%d", k.Next, k.Checksum) }}']
    for j, queue in enumerate(queues):
        lines.append(f'if k.n{j} != {len(queue)} {{ t.Fatal("periodic marking differs") }}')
        for value in queue:
            lines.append(f'if k.pop{j}() != {value} {{ t.Fatal("feedback token differs") }}')
    lines.append('}')
    lines += [f'func Test{name}NoStepAllocations(t *testing.T) {{', f'k := New{name}()',
              'allocs := testing.AllocsPerRun(10000, func() { k.Step() })',
              'if allocs != 0 { t.Fatalf("allocations/step: %v", allocs) }',
              't.Logf("allocations/step: %v", allocs)', '}']
    tests.append('\n'.join(lines))
    certs.append({'fixture': i, **cert, **verify(actors, edges, cert)})
(root / 'generated.go').write_text('\n\n'.join(code) + '\n')
(root / 'generated_test.go').write_text('\n\n'.join(tests) + '\n')
(root / 'certificates.json').write_text(json.dumps(certs, indent=2) + '\n')
print('Generated four kernels, eight Go tests and their certificates.')
