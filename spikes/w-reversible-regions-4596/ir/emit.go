package ir

import (
	"fmt"
	"sort"
	"strings"
)

// EmitCase is one admitted case to emit.
type EmitCase struct {
	Prog   *Program
	GoName string
	Kind   string
}

// FuncSize is the emitted code size of one direction, in bytes and lines.
type FuncSize struct {
	ForwardBytes, ForwardLines int
	InverseBytes, InverseLines int
}

// RegName maps a register index to its Go identifier in emitted code.
func RegName(i int) string {
	if i == KeyReg {
		return "key"
	}
	return fmt.Sprintf("x%d", i)
}

// GoName converts a snake_case case name to an exported Go identifier.
func GoName(name string) string {
	var b strings.Builder
	up := true
	for _, r := range name {
		if r == '_' || r == '-' {
			up = true
			continue
		}
		if up {
			if r >= 'a' && r <= 'z' {
				r = r - 'a' + 'A'
			}
			up = false
		}
		b.WriteRune(r)
	}
	return b.String()
}

type usage struct {
	bits   bool
	binary bool
	tmp    int
	sboxes map[string]bool
}

func u64(v uint64) string { return fmt.Sprintf("0x%x", v) }

// EmitFile renders a complete Go package with forward and mechanically derived
// inverse functions plus a registry. It also returns per-case code sizes.
func EmitFile(cases []EmitCase) (string, map[string]FuncSize, error) {
	u := &usage{sboxes: map[string]bool{}}
	sizes := map[string]FuncSize{}

	type fnText struct {
		name string
		body string
	}
	var fns []fnText

	for _, c := range cases {
		if diags := Check(c.Prog); len(diags) != 0 {
			return "", nil, fmt.Errorf("case %s is not admitted: %s", c.Prog.Name, diags[0])
		}
		inv := Invert(c.Prog)

		fwd, err := emitFunc("Forward"+c.GoName, c.Prog.Stmts, u)
		if err != nil {
			return "", nil, fmt.Errorf("%s forward: %w", c.Prog.Name, err)
		}
		bwd, err := emitFunc("Inverse"+c.GoName, inv.Stmts, u)
		if err != nil {
			return "", nil, fmt.Errorf("%s inverse: %w", c.Prog.Name, err)
		}
		fns = append(fns, fnText{"Forward" + c.GoName, fwd}, fnText{"Inverse" + c.GoName, bwd})
		sizes[c.Prog.Name] = FuncSize{
			ForwardBytes: len(fwd), ForwardLines: strings.Count(fwd, "\n"),
			InverseBytes: len(bwd), InverseLines: strings.Count(bwd, "\n"),
		}
	}

	var b strings.Builder
	b.WriteString("// Code generated by cmd/revsynth for issue #4596. DO NOT EDIT.\n")
	b.WriteString("//\n// Forward functions and their mechanically derived inverses; state is 8 owned\n")
	b.WriteString("// words plus the immutable key word.\n\npackage gen\n\n")

	var imp []string
	if u.binary {
		imp = append(imp, "\t\"encoding/binary\"")
	}
	if u.bits {
		imp = append(imp, "\t\"math/bits\"")
	}
	if len(imp) > 0 {
		b.WriteString("import (\n" + strings.Join(imp, "\n") + "\n)\n\n")
	}

	b.WriteString("// State is the owned region state, 8 fixed-width words.\n")
	b.WriteString("type State struct {\n\tX0, X1, X2, X3, X4, X5, X6, X7 uint64\n}\n\n")

	// Declared substitution tables, emitted once each.
	var names []string
	for n := range u.sboxes {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		sb := findSbox(cases, n)
		if sb == nil {
			return "", nil, fmt.Errorf("table %q used but not declared", n)
		}
		fmt.Fprintf(&b, "// sbox%sTable is the declared affine table y = (x*0x%02x mod 256) ^ 0x%02x (bijective: %v).\n", n, sb.A, sb.B, sb.Bijective)
		fmt.Fprintf(&b, "var sbox%sTable = [256]byte{\n", n)
		for i := 0; i < 256; i += 16 {
			b.WriteString("\t")
			for j := 0; j < 16; j++ {
				fmt.Fprintf(&b, "0x%02x, ", sb.Table[i+j])
			}
			b.WriteString("\n")
		}
		b.WriteString("}\n\n")
		fmt.Fprintf(&b, "// sbox%sInv is derived by table inversion, not by trusting the declaration.\n", n)
		fmt.Fprintf(&b, "var sbox%sInv = [256]byte{\n", n)
		for i := 0; i < 256; i += 16 {
			b.WriteString("\t")
			for j := 0; j < 16; j++ {
				fmt.Fprintf(&b, "0x%02x, ", sb.Inv[i+j])
			}
			b.WriteString("\n")
		}
		b.WriteString("}\n\n")
		fmt.Fprintf(&b, "func sboxApply%s(v uint64) uint64 {\n", n)
		b.WriteString("\tvar w [8]byte\n\tbinary.LittleEndian.PutUint64(w[:], v)\n")
		b.WriteString("\tfor i := range w {\n\t\tw[i] = sbox" + n + "Table[w[i]]\n\t}\n")
		b.WriteString("\treturn binary.LittleEndian.Uint64(w[:])\n}\n\n")
		fmt.Fprintf(&b, "func sboxApplyInv%s(v uint64) uint64 {\n", n)
		b.WriteString("\tvar w [8]byte\n\tbinary.LittleEndian.PutUint64(w[:], v)\n")
		b.WriteString("\tfor i := range w {\n\t\tw[i] = sbox" + n + "Inv[w[i]]\n\t}\n")
		b.WriteString("\treturn binary.LittleEndian.Uint64(w[:])\n}\n\n")
	}

	for _, f := range fns {
		b.WriteString(f.body)
		b.WriteString("\n")
	}

	b.WriteString("// Case ties a case name to its generated forward/inverse pair.\n")
	b.WriteString("type Case struct {\n\tName string\n\tKind string\n\tHasBranch bool\n\tForward func(State, uint64) State\n\tInverse func(State, uint64) State\n}\n\n")
	b.WriteString("var Cases = []Case{\n")
	for _, c := range cases {
		fmt.Fprintf(&b, "\t{Name: %q, Kind: %q, HasBranch: %v, Forward: Forward%s, Inverse: Inverse%s},\n",
			c.Prog.Name, c.Kind, c.Prog.IfCount > 0, c.GoName, c.GoName)
	}
	b.WriteString("}\n")
	return b.String(), sizes, nil
}

func findSbox(cases []EmitCase, name string) *Sbox {
	for _, c := range cases {
		if sb, ok := c.Prog.Sboxes[name]; ok {
			return sb
		}
	}
	return nil
}

func emitFunc(name string, stmts []*Stmt, u *usage) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "func %s(s State, key uint64) State {\n", name)
	b.WriteString("\tx0, x1, x2, x3, x4, x5, x6, x7 := s.X0, s.X1, s.X2, s.X3, s.X4, s.X5, s.X6, s.X7\n")
	if err := emitStmts(&b, stmts, 1, u); err != nil {
		return "", err
	}
	b.WriteString("\treturn State{x0, x1, x2, x3, x4, x5, x6, x7}\n}\n")
	return b.String(), nil
}

func emitStmts(b *strings.Builder, stmts []*Stmt, depth int, u *usage) error {
	ind := strings.Repeat("\t", depth)
	for _, st := range stmts {
		switch st.Op {
		case OpAdd:
			fmt.Fprintf(b, "%s%s += %s\n", ind, RegName(st.Reg), u64(st.Imm))
		case OpSub:
			fmt.Fprintf(b, "%s%s -= %s\n", ind, RegName(st.Reg), u64(st.Imm))
		case OpAddV:
			fmt.Fprintf(b, "%s%s += %s\n", ind, RegName(st.Reg), RegName(st.Reg2))
		case OpSubV:
			fmt.Fprintf(b, "%s%s -= %s\n", ind, RegName(st.Reg), RegName(st.Reg2))
		case OpXor:
			fmt.Fprintf(b, "%s%s ^= %s\n", ind, RegName(st.Reg), RegName(st.Reg2))
		case OpXorI:
			fmt.Fprintf(b, "%s%s ^= %s\n", ind, RegName(st.Reg), u64(st.Imm))
		case OpRotl:
			u.bits = true
			fmt.Fprintf(b, "%s%s = bits.RotateLeft64(%s, %d)\n", ind, RegName(st.Reg), RegName(st.Reg), st.Imm%64)
		case OpRotr:
			u.bits = true
			fmt.Fprintf(b, "%s%s = bits.RotateLeft64(%s, -%d)\n", ind, RegName(st.Reg), RegName(st.Reg), st.Imm%64)
		case OpSwap:
			fmt.Fprintf(b, "%s%s, %s = %s, %s\n", ind, RegName(st.Reg), RegName(st.Reg2), RegName(st.Reg2), RegName(st.Reg))
		case OpPerm:
			// Emit one rotation per cycle, so the generated code contains no
			// self-assignment and needs a single temporary per cycle.
			var seen [NumRegs]bool
			for start := 0; start < NumRegs; start++ {
				if seen[start] {
					continue
				}
				if st.Perm[start] == start {
					seen[start] = true
					continue
				}
				var cyc []int
				for cur := start; !seen[cur]; cur = st.Perm[cur] {
					seen[cur] = true
					cyc = append(cyc, cur)
				}
				tmp := fmt.Sprintf("pt%d", u.tmp)
				u.tmp++
				fmt.Fprintf(b, "%s%s := %s\n", ind, tmp, RegName(cyc[0]))
				for i := 0; i < len(cyc)-1; i++ {
					fmt.Fprintf(b, "%s%s = %s\n", ind, RegName(cyc[i]), RegName(cyc[i+1]))
				}
				fmt.Fprintf(b, "%s%s = %s\n", ind, RegName(cyc[len(cyc)-1]), tmp)
			}
		case OpSbox:
			u.binary = true
			u.sboxes[st.Sbox] = true
			fn := "sboxApply" + st.Sbox
			if st.InvSbox {
				fn = "sboxApplyInv" + st.Sbox
			}
			fmt.Fprintf(b, "%s%s = %s(%s)\n", ind, RegName(st.Reg), fn, RegName(st.Reg))
		case OpIf:
			fmt.Fprintf(b, "%sif (%s >> uint(%d)) & 1 == %d {\n", ind, RegName(st.Reg), st.Bit, st.BitVal)
			if err := emitStmts(b, st.Then, depth+1, u); err != nil {
				return err
			}
			if len(st.Else) > 0 {
				fmt.Fprintf(b, "%s} else {\n", ind)
				if err := emitStmts(b, st.Else, depth+1, u); err != nil {
					return err
				}
			}
			fmt.Fprintf(b, "%s}\n", ind)
		default:
			return fmt.Errorf("line %d: cannot emit refused statement %s", st.Line, st.Op)
		}
	}
	return nil
}
