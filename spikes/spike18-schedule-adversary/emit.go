package periodic

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
)

// Emit accepts only verified witnesses and the closed primitive registry.
// It always emits queue guards; there is no unchecked/fast emission mode.
func Emit(g Graph, c Certificate, pkg string) ([]byte, error) {
	if _, err := Verify(g, c); err != nil {
		return nil, err
	}
	if !token.IsIdentifier(pkg) || pkg == "_" {
		return nil, fmt.Errorf("invalid package name %q", pkg)
	}
	var b bytes.Buffer
	p := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }
	p("// Code generated by the W-018 schedule adversary. DO NOT EDIT.")
	p("// Graph SHA256: %s", c.GraphSHA256)
	p("// Payload excludes indices, actor state, padding, stacks and runtime.")
	p("package %s", pkg)
	p("const PayloadBytes uint64 = %d", c.PayloadBytes)
	p("type Kernel struct {")
	for i, cap := range c.Capacities {
		p("q%d [%d]uint64; r%d, w%d, n%d int", i, cap, i, i, i)
	}
	sinks := []int{}
	for i, a := range g.Actors {
		if a.Op == "source" || a.Op == "sink" {
			p("state%d uint64", i)
		}
		if a.Op == "sink" {
			sinks = append(sinks, i)
		}
	}
	p("}")
	for i, e := range g.Edges {
		p("func (k *Kernel) pop%d() uint64 {", i)
		p("if k.n%d <= 0 { panic(\"FIFO underflow: %s\") }", i, e.Name)
		p("v := k.q%d[k.r%d]; k.r%d = (k.r%d + 1) %% %d; k.n%d--; return v }", i, i, i, i, c.Capacities[i], i)
		p("func (k *Kernel) push%d(v uint64) {", i)
		p("if k.n%d >= %d { panic(\"FIFO overflow: %s\") }", i, c.Capacities[i], e.Name)
		p("k.q%d[k.w%d] = v; k.w%d = (k.w%d + 1) %% %d; k.n%d++ }", i, i, i, i, c.Capacities[i], i)
	}
	p("// New initializes all FIFO tokens. The zero value is not initialized.")
	p("func New() *Kernel { k := new(Kernel)")
	for i, e := range g.Edges {
		for j, v := range e.Initial {
			p("k.q%d[%d] = %d", i, j, v)
		}
		p("k.n%d = %d; k.w%d = %d", i, len(e.Initial), i, len(e.Initial)%c.Capacities[i])
	}
	p("return k }")
	p("// Step executes exactly one certified period. Do not call concurrently.")
	p("// Successful execution uses no heap allocation or blocking primitives.")
	p("func (k *Kernel) Step() [%d]uint64 {", len(sinks))
	for _, a := range c.Schedule {
		p("{ var v uint64")
		for i, e := range g.Edges {
			if e.To != a {
				continue
			}
			p("for j := 0; j < %d; j++ {", e.Consume)
			p("v += k.pop%d()", i)
			p("}")
		}
		switch g.Actors[a].Op {
		case "source":
			p("k.state%d++; v = k.state%d", a, a)
		case "scale":
			p("v *= uint64(%d)", g.Actors[a].Factor)
		case "sink":
			p("k.state%d += v", a)
		}
		for i, e := range g.Edges {
			if e.From != a {
				continue
			}
			p("for j := 0; j < %d; j++ {", e.Produce)
			p("k.push%d(v)", i)
			p("}")
		}
		p("}")
	}
	for i, e := range g.Edges {
		p("if k.n%d != %d { panic(\"nonperiodic FIFO: %s\") }", i, len(e.Initial), e.Name)
	}
	p("return [%d]uint64{", len(sinks))
	for _, a := range sinks {
		p("k.state%d,", a)
	}
	p("} }")
	return format.Source(b.Bytes())
}
