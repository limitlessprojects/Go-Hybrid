//! `hyb build` must not overwrite user-owned Go source at its implicit
//! `<output>.go` path. Only marked output from a previous build may be refreshed.

use std::fs;
use std::path::PathBuf;
use std::process::{Command, Output};
use std::sync::atomic::{AtomicUsize, Ordering};

static NEXT: AtomicUsize = AtomicUsize::new(0);
const GENERATED_HEADER_PREFIX: &str = "// Code generated by hyb from ";

struct Inputs(PathBuf);

impl Inputs {
    fn new() -> Self {
        let root = std::env::temp_dir().join(format!(
            "hyb-build-output-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed)
        ));
        fs::create_dir(&root).expect("create unique inputs directory");
        fs::write(root.join("good.hy"), "fn main() {}\n").unwrap();
        Self(root)
    }

    fn emit_go(&self) -> Output {
        Command::new(env!("CARGO_BIN_EXE_hyb"))
            .args(["build", "good.hy", "-o", "app", "--emit-go"])
            .env("HYB_ALLOW_TOOLCHAIN_DRIFT", "1")
            .current_dir(&self.0)
            .output()
            .expect("run actual hyb build CLI")
    }
}

impl Drop for Inputs {
    fn drop(&mut self) {
        fs::remove_dir_all(&self.0).expect("remove test-owned inputs");
    }
}

fn assert_exit(output: &Output, code: i32) {
    assert_eq!(
        output.status.code(),
        Some(code),
        "unexpected build result: stdout={}, stderr={}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

#[test]
fn hand_written_go_output_and_existing_binary_are_preserved() {
    let inputs = Inputs::new();
    let go_source = b"package main\n\n// Hand-written source must survive a build.\n";
    let binary = b"existing binary sentinel\0";
    fs::write(inputs.0.join("app.go"), go_source).unwrap();
    fs::write(inputs.0.join("app"), binary).unwrap();

    let output = inputs.emit_go();

    assert_exit(&output, 2);
    assert!(String::from_utf8_lossy(&output.stderr).contains("app.go"));
    assert_eq!(fs::read(inputs.0.join("app.go")).unwrap(), go_source);
    assert_eq!(fs::read(inputs.0.join("app")).unwrap(), binary);
}

#[test]
fn non_utf8_go_output_is_preserved() {
    let inputs = Inputs::new();
    // Even a recognizable header does not authorize replacing an output
    // whose contents could not be read successfully.
    let existing =
        b"// Code generated by hyb from good.hy. DO NOT EDIT.\n\npackage main\n// \xff\n";
    fs::write(inputs.0.join("app.go"), existing).unwrap();

    let output = inputs.emit_go();

    assert_exit(&output, 2);
    assert!(String::from_utf8_lossy(&output.stderr).contains("app.go"));
    assert_eq!(fs::read(inputs.0.join("app.go")).unwrap(), existing);
    assert!(
        !inputs.0.join("app").exists(),
        "no binary on a refused build"
    );
}

#[test]
fn normal_build_preserves_user_source_and_existing_binary() {
    let inputs = Inputs::new();
    let source = b"package main\n\n// Hand-written Go source.\n";
    let binary = b"existing executable";
    fs::write(inputs.0.join("app.go"), source).unwrap();
    fs::write(inputs.0.join("app"), binary).unwrap();

    let output = Command::new(env!("CARGO_BIN_EXE_hyb"))
        .args(["build", "good.hy", "-o", "app"])
        .env("HYB_ALLOW_TOOLCHAIN_DRIFT", "1")
        .current_dir(&inputs.0)
        .output()
        .expect("run actual hyb build CLI");

    assert_exit(&output, 2);
    assert_eq!(fs::read(inputs.0.join("app.go")).unwrap(), source);
    assert_eq!(fs::read(inputs.0.join("app")).unwrap(), binary);
}

#[test]
fn legacy_unmarked_output_requires_an_explicit_migration() {
    let inputs = Inputs::new();
    let legacy = b"package main\n\nfunc main() {\n}\n";
    fs::write(inputs.0.join("app.go"), legacy).unwrap();

    let output = inputs.emit_go();

    assert_exit(&output, 2);
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(stderr.contains("old generated artifact"), "{stderr}");
    assert!(stderr.contains("choose another -o path"), "{stderr}");
    assert_eq!(fs::read(inputs.0.join("app.go")).unwrap(), legacy);
}

#[test]
fn fresh_build_output_has_a_generated_source_header() {
    let inputs = Inputs::new();

    let output = inputs.emit_go();

    assert_exit(&output, 0);
    let generated = fs::read_to_string(inputs.0.join("app.go")).unwrap();
    assert!(
        generated.starts_with(GENERATED_HEADER_PREFIX),
        "{generated}"
    );
    let header = generated.lines().next().unwrap();
    assert!(header.contains("good.hy"), "source is identified: {header}");
    assert!(header.contains("DO NOT EDIT."), "{header}");
    assert!(generated.contains("package main"), "{generated}");
    assert!(
        !inputs.0.join("app").exists(),
        "--emit-go does not build a binary"
    );
}

#[test]
fn previously_generated_output_can_be_updated_and_rebuilt() {
    let inputs = Inputs::new();
    assert_exit(&inputs.emit_go(), 0);
    let before = fs::read(inputs.0.join("app.go")).unwrap();
    fs::write(inputs.0.join("good.hy"), "fn main() {}\nfn helper() {}\n").unwrap();

    let update = inputs.emit_go();

    assert_exit(&update, 0);
    let updated = fs::read_to_string(inputs.0.join("app.go")).unwrap();
    assert!(updated.starts_with(GENERATED_HEADER_PREFIX), "{updated}");
    assert!(updated.contains("func helper("), "{updated}");
    assert_ne!(
        updated.as_bytes(),
        before.as_slice(),
        "source changes are emitted"
    );

    assert_exit(&inputs.emit_go(), 0);
    assert_eq!(
        fs::read(inputs.0.join("app.go")).unwrap(),
        updated.as_bytes(),
        "rebuilding unchanged source preserves generated content"
    );
}
